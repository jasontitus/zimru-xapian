//! Regenerate the search engine's Unicode 18 tables from its pinned ICU4X test oracle.
use icu_normalizer::{
    DecomposingNormalizerBorrowed,
    properties::{
        CanonicalCombiningClassMap, CanonicalComposition, CanonicalDecomposition, Decomposed,
    },
};
use icu_properties::{
    CodePointMapData,
    props::{GeneralCategory as GC, GeneralCategoryGroup as G},
};
use std::{collections::BTreeMap, fmt::Write, fs, path::Path};

fn main() {
    let verify = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        _ => panic!("usage: generate_unicode [--check]"),
    };
    let nfd = DecomposingNormalizerBorrowed::new_nfd();
    let gc = CodePointMapData::<GC>::new();
    let words = G::Letter
        .union(G::Mark)
        .union(G::Number)
        .union(G::ConnectorPunctuation);
    let stem = G::LowercaseLetter
        .union(G::TitlecaseLetter)
        .union(G::ModifierLetter)
        .union(G::OtherLetter);
    let ccc = CanonicalCombiningClassMap::new();
    let compose = CanonicalComposition::new();
    let raw = CanonicalDecomposition::new();
    let mut flags = vec![0u8; 0x110000];
    let mut mappings =
        String::from("// Generated by examples/generate_unicode.rs. Unicode-3.0.\nmatch c {\n");
    let mut extra_pairs = Vec::new();
    for c in (0..=0x10ffff).filter_map(char::from_u32) {
        let group = gc.get(c);
        let mark = G::Mark.contains(group);
        // Removing marks eliminates every nonzero canonical combining class.
        // Reordering inside a combining sequence therefore cannot reorder any survivors.
        assert!(mark || ccc.get_u8(c) == 0);
        if let Decomposed::Expansion(a, b) = raw.decompose(c)
            && !G::Mark.contains(gc.get(a))
            && !G::Mark.contains(gc.get(b))
            && compose.compose(a, b) == Some(c)
            && !matches!(c, '\u{ac00}'..='\u{d7a3}')
        {
            extra_pairs.push((a, b, c));
        }
        let bits = u8::from(words.contains(group))
            | (u8::from(group == GC::DecimalNumber) << 1)
            | (u8::from(stem.contains(group)) << 2)
            | (u8::from(mark) << 3);
        let stripped: String = nfd
            .normalize_iter(std::iter::once(c))
            .filter(|&ch| !G::Mark.contains(gc.get(ch)))
            .collect();
        if mark {
            assert!(
                stripped.is_empty(),
                "mark decomposes to a surviving starter: {c:?}"
            );
        }
        let replaced = !mark && !matches!(c, '\u{ac00}'..='\u{d7a3}') && !stripped.chars().eq([c]);
        if replaced {
            writeln!(
                mappings,
                "    '{}' => \"{}\",",
                c.escape_unicode(),
                stripped
                    .chars()
                    .flat_map(char::escape_unicode)
                    .collect::<String>()
            )
            .unwrap();
        }
        flags[c as usize] = bits | (u8::from(replaced) << 4);
    }
    let mut compositions = String::from(
        "// Generated by examples/generate_unicode.rs. Unicode-3.0.\nmatch (first, second) {\n",
    );
    for (a, b, c) in extra_pairs {
        // A precomposed Hangul syllable starts with a leading Jamo in NFD. No
        // preceding starter can compose with that Jamo, so these syllables can
        // pass through as a unit (and an LV syllable can still accept a trailing Jamo).
        assert!(!matches!(b, '\u{1100}'..='\u{1112}'));
        flags[b as usize] |= 32;
        writeln!(
            compositions,
            "    ('{}', '{}') => Some('{}'),",
            a.escape_unicode(),
            b.escape_unicode(),
            c.escape_unicode()
        )
        .unwrap();
    }
    compositions.push_str("    _ => None,\n}\n");
    mappings.push_str("    _ => unreachable!(\"missing generated Unicode decomposition\"),\n}\n");
    let mut unique_pages = BTreeMap::new();
    let mut pages = Vec::new();
    let mut directory = Vec::new();
    for page in flags.as_chunks::<256>().0 {
        let index = *unique_pages.entry(page).or_insert_with(|| {
            let index = u8::try_from(pages.len() / 256).expect("page index exceeds u8");
            pages.extend_from_slice(page);
            index
        });
        directory.push(index);
    }
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/unicode");
    for (name, data) in [
        ("flags.pages", pages),
        ("flags.index", directory),
        ("decompositions.rs", mappings.into_bytes()),
        ("compositions.rs", compositions.into_bytes()),
    ] {
        if verify {
            assert_eq!(fs::read(root.join(name)).unwrap(), data, "{name} is stale");
        } else {
            fs::write(root.join(name), data).unwrap();
        }
    }
}
